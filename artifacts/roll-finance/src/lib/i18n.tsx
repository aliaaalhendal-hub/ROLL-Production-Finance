type I18nContextType = {
  lang: Language;
  setLang: (lang: Language) => void;
  t: (key: string) => string;
  tStatus: (status: string) => string;
};

const I18nContext = createContext<I18nContextType | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Language>(() => {
    return (localStorage.getItem("roll-lang") as Language) || "en";
  });

  useEffect(() => {
    localStorage.setItem("roll-lang", lang);
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    document.documentElement.lang = lang;
  }, [lang]);

  const t = (key: string) => {
    const dict = lang === "ar" ? ar : en;
    return dict[key] || key;
  };

  const tStatus = (status: string) => {
    if (!status) return "";
    const words = status.toLowerCase().split(/[^a-z0-9]+/).filter(Boolean);
    const keyStr = "status." + words.map((word, index) =>
      index === 0 ? word : word.charAt(0).toUpperCase() + word.slice(1)
    ).join("");
    const dict = lang === "ar" ? ar : en;
    return dict[keyStr] || status;
  };

  return (
    <I18nContext.Provider value={{ lang, setLang, t, tStatus }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useTranslation() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useTranslation must be used within I18nProvider");
  return ctx;
}
